// Generates src/data/world-map.ts: a line world map (land outline) projected
// equirectangular into a 0 0 360 180 viewBox. Run via `npm run genmap`.
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { feature } from 'topojson-client';

const require = createRequire(import.meta.url);
const topo = require('world-atlas/land-110m.json');
const land = feature(topo, topo.objects.land);

const project = ([lon, lat]) => [lon + 180, 90 - lat]; // equirectangular, 1 unit/deg

const ringToPath = (ring) =>
  ring
    .map((pt, i) => {
      const [x, y] = project(pt);
      return `${i === 0 ? 'M' : 'L'}${x.toFixed(2)} ${y.toFixed(2)}`;
    })
    .join('') + 'Z';

const polygonToPath = (rings) => rings.map(ringToPath).join('');

let d = '';
const features = land.type === 'FeatureCollection' ? land.features : [land];
for (const f of features) {
  const g = f.geometry ?? f;
  if (g.type === 'Polygon') d += polygonToPath(g.coordinates);
  else if (g.type === 'MultiPolygon') g.coordinates.forEach((poly) => (d += polygonToPath(poly)));
}

const out =
  `// AUTO-GENERATED by scripts/generate-world-map.mjs — do not edit by hand.\n` +
  `// Regenerate with: npm run genmap\n` +
  `export const worldMap = {\n  viewBox: '0 0 360 180',\n  d: '${d}',\n} as const;\n`;
writeFileSync('src/data/world-map.ts', out);
console.log(`Wrote src/data/world-map.ts (path ${d.length} chars)`);
